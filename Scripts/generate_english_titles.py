def main() -> int:
    with open("Poetry/TangShiThreeHundred.json") as f:
        tang = json.load(f)
    with open("Poetry/SongCiThreeHundred.json") as f:
        song = json.load(f)

    titles = {}

    tang_ids = {e["id"] for e in tang}
    missing_tang = tang_ids - TANG.keys()
    extra_tang = TANG.keys() - tang_ids
    for e in tang:
        titles[f"tangshi-300-{e['id']}"] = TANG[e["id"]]

    song_indexes = set(range(1, len(song) + 1))
    missing_song = song_indexes - SONG.keys()
    extra_song = SONG.keys() - song_indexes
    for i in range(1, len(song) + 1):
        titles[f"songci-300-{i}"] = SONG[i]

    problems = []
    if missing_tang:
        problems.append(f"Tang missing ids: {sorted(missing_tang)}")
    if extra_tang:
        problems.append(f"Tang extra ids: {sorted(extra_tang)}")
    if missing_song:
        problems.append(f"Song missing indexes: {sorted(missing_song)}")
    if extra_song:
        problems.append(f"Song extra indexes: {sorted(extra_song)}")
    if problems:
        for p in problems:
            print(p, file=sys.stderr)
        return 1

    with open("Poetry/ClassicPoemTitle-en.json", "w") as f:
        json.dump({"titles": titles}, f, ensure_ascii=False, indent=2, sort_keys=True)
        f.write("\n")

    print(f"OK: wrote {len(titles)} titles "
          f"({len(tang)} Tang, {len(song)} Song Ci)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
